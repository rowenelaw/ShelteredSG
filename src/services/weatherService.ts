export function classifyRainSeverity(mmHr: number): RainSeverity {
  if (mmHr < 0.5) return 'dry';
  if (mmHr < 10) return 'light';
  if (mmHr < 22) return 'moderate';
  if (mmHr < 34) return 'heavy';
  return 'thundery';
}

export function getWeatherSnapshot(
  scenarioId: WeatherScenarioId,
  forecastOffsetMin = 0
): WeatherSnapshot {
  const base = BASE_SCENARIOS[scenarioId];
  const scenarioMeta = WEATHER_SCENARIOS.find((s) => s.id === scenarioId) ?? WEATHER_SCENARIOS[0];

  // Subtle spatial drift & decay/intensification over forecastOffsetMin (for radar playback)
  const driftFactor = forecastOffsetMin / 60;
  const cells: RainCell[] = base.cells.map((cell, idx) => {
    if (forecastOffsetMin === 0 || scenarioId === 'dry_clear') {
      return { ...cell };
    }
    const latShift = scenarioId === 'west_squall' ? 0.008 * driftFactor : -0.01 * driftFactor;
    const lngShift = scenarioId === 'west_squall' ? 0.028 * driftFactor : -0.015 * driftFactor;
    const intensityMultiplier = Math.max(
      0.15,
      1 - driftFactor * 0.22 + Math.sin(idx + driftFactor * 2) * 0.14
    );
    const nextRain = Math.round(cell.rainfallMmHr * intensityMultiplier * 10) / 10;
    const severity = classifyRainSeverity(nextRain);
    return {
      ...cell,
      lat: cell.lat + latShift,
      lng: cell.lng + lngShift,
      rainfallMmHr: nextRain,
      severity,
      lightningRisk: nextRain >= 24,
    };
  });

  const maxRainfallMmHr = cells.reduce((max, c) => Math.max(max, c.rainfallMmHr), 0);

  return {
    scenarioId,
    scenarioLabel: scenarioMeta.label,
    updatedAtIso: new Date().toISOString(),
    islandSummary: base.islandSummary,
    maxRainfallMmHr,
    windSummary: base.windSummary,
    cells,
  };
}

export function sampleRainAtCoords(
  lat: number,
  lng: number,
  snapshot: WeatherSnapshot
): { rainfallMmHr: number; severity: RainSeverity; nearestArea: string } {
  if (snapshot.cells.length === 0) {
    return { rainfallMmHr: 0, severity: 'dry', nearestArea: 'Singapore' };
  }

  let weightedSum = 0;
  let weightTotal = 0;
  let nearestArea = snapshot.cells[0].areaName;
  let minDist = Infinity;

  for (const cell of snapshot.cells) {
    const distKm = haversineDistanceKm({ lat, lng }, { lat: cell.lat, lng: cell.lng });
    if (distKm < minDist) {
      minDist = distKm;
      nearestArea = cell.areaName;
    }
    const influence = Math.max(0, 1 - distKm / (cell.radiusKm * 1.45));
    const weight = influence * influence + 0.02 / (distKm + 0.5);
    weightedSum += cell.rainfallMmHr * weight;
    weightTotal += weight;
  }

  const rainfallMmHr =
    weightTotal > 0 ? Math.round((weightedSum / weightTotal) * 10) / 10 : 0;

  return {
    rainfallMmHr,
    severity: classifyRainSeverity(rainfallMmHr),
    nearestArea,
  };
}
